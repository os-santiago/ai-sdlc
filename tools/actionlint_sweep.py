#!/usr/bin/env python3
"""Emit a synthetic caller workflow that `uses:` every local action.

actionlint v1.7.x cannot lint action.yml files as direct operands — it parses
every file argument as a *workflow* — but it DOES check local actions
transitively when a linted workflow references them via `uses: ./...`
(actionlint v1.7.0+). Linting this generated caller therefore covers every
shipped action, including ones only reachable from consumer repos via
`owner/repo/path@ref` — the blind spot behind issue #130.

Usage:  python3 tools/actionlint_sweep.py [actions-dir] [out-file]
Defaults: .github/actions, stdout. The emitted `uses:` paths are
repo-root-relative, so the generated file may live anywhere inside the repo
(actionlint resolves the project root by walking up to .github/).

Pure stdlib — required inputs are found by indentation scan instead of
PyYAML so the tool runs on a bare python3. Fail-safe both ways: a missed
required input makes actionlint report "input <name> is required", and a
spurious `with:` key makes it report "not defined" — either direction fails
loudly rather than linting a partial surface.
"""
import os
import re
import sys

TOP_KEY = re.compile(r'^\S')
INPUTS_KEY = re.compile(r'^inputs:\s*(?:#.*)?$')
INPUT_NAME = re.compile(r'^  ([A-Za-z0-9_-]+):\s*(?:#.*)?$')
INPUT_FIELD = re.compile(r'^    ([A-Za-z0-9_-]+):\s*(.*?)\s*$')


def required_inputs(action_file):
    """Input names declared `required: true` under the top-level `inputs:` map."""
    req = []
    in_inputs = False
    cur = None
    cur_required = False

    def flush():
        if cur is not None and cur_required:
            req.append(cur)

    with open(action_file, encoding='utf-8') as fh:
        for line in fh:
            if TOP_KEY.match(line):
                flush()
                cur, cur_required = None, False
                in_inputs = bool(INPUTS_KEY.match(line.rstrip()))
                continue
            if not in_inputs:
                continue
            m = INPUT_NAME.match(line)
            if m:
                flush()
                cur, cur_required = m.group(1), False
                continue
            f = INPUT_FIELD.match(line)
            if (f and cur is not None and f.group(1) == 'required'
                    and f.group(2).strip().strip('\'"').lower() == 'true'):
                cur_required = True
        flush()
    return req


def main():
    actions_dir = sys.argv[1] if len(sys.argv) > 1 else '.github/actions'
    out_path = sys.argv[2] if len(sys.argv) > 2 else None

    lines = [
        '# GENERATED by tools/actionlint_sweep.py — do not edit.',
        '# Synthetic caller exercising every local action so actionlint checks',
        '# each action.yml transitively via `uses:` (issue #130).',
        'name: actionlint-actions-sweep',
        'on:',
        '  workflow_call:',
        'jobs:',
        '  sweep:',
        '    runs-on: ubuntu-latest',
        '    steps:',
    ]

    count = 0
    for entry in sorted(os.listdir(actions_dir)):
        action_dir = os.path.join(actions_dir, entry)
        action_file = None
        for candidate in ('action.yml', 'action.yaml'):
            p = os.path.join(action_dir, candidate)
            if os.path.isfile(p):
                action_file = p
                break
        if action_file is None:
            continue
        count += 1
        lines.append(f'      - uses: ./.github/actions/{entry}')
        reqs = required_inputs(action_file)
        if reqs:
            lines.append('        with:')
            for name in reqs:
                lines.append(f"          {name}: 'actionlint-sweep'")

    text = '\n'.join(lines) + '\n'
    if out_path:
        with open(out_path, 'w', encoding='utf-8') as fh:
            fh.write(text)
    else:
        sys.stdout.write(text)
    print(f'[i] actionlint sweep: {count} local action(s) referenced',
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
